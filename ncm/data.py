"""Corpus building and batching.

A dataset directory holds a BPE vocab and train/val corpora. A corpus is a flat token array plus
per-document offsets (header | context | completion). Only completion tokens are targets; training
windows (prefix, target block) are cut on the fly, so block_len/prefix_len can change without
re-tokenizing.
"""
from __future__ import annotations

import dataclasses
import hashlib
import json
import os
from pathlib import Path
from typing import Iterable, Iterator

import numpy as np

from . import chat
from .config import ChatConfig
from .text import BPE, EOS, PAD, build_prefix
from .tools import TOOL_NAMES

LANGS: dict[str, tuple[str, ...]] = {
    "java": (".java", "pom.xml", "build.gradle", "settings.gradle", ".properties"),
    "kotlin": (".kt", ".kts"),
    "scala": (".scala", ".sbt"),
    "go": (".go", "go.mod"),
    "rust": (".rs", "Cargo.toml"),
    "typescript": (".ts", ".tsx", ".mts", ".cts", "package.json", "tsconfig.json"),
    "javascript": (".js", ".mjs", ".cjs", ".jsx", "package.json"),
    "python": (".py", "pyproject.toml", "requirements.txt"),
    "csharp": (".cs", ".csproj"),
    "elixir": (".ex", ".exs"),
    "erlang": (".erl", ".hrl"),
    "ruby": (".rb", ".rake", "Gemfile"),
    "php": (".php", "composer.json"),
}
# Service glue that backend/distributed work lives in; opt in with --infra.
INFRA = (".proto", ".sql", ".graphql", ".gql", ".yaml", ".yml", ".tf", ".sh", "Dockerfile", "Makefile")
SKIP_DIRS = {".git", ".hg", ".svn", "node_modules", "vendor", "third_party", "target", "build", "dist", "out",
             "bin", "obj", ".gradle", ".idea", ".vscode", "__pycache__", ".venv", "venv", ".tox", ".next", "coverage"}
GENERATED_MARKERS = ("do not edit", "@generated", "auto-generated", "autogenerated", "code generated by")


def patterns_for(langs: Iterable[str], infra: bool = False) -> tuple[str, ...]:
    pats = []
    for lang in langs:
        if lang not in LANGS:
            raise KeyError(f"unknown language {lang!r}; choose from {sorted(LANGS)}")
        pats += LANGS[lang]
    return tuple(dict.fromkeys(pats + (list(INFRA) if infra else [])))


def matches(name: str, patterns: tuple[str, ...]) -> bool:
    low = name.lower()
    return any(low.endswith(p) if p.startswith(".") else (name == p or name.startswith(p + "."))
               for p in patterns)


def read_source(path: Path, max_bytes: int) -> str | None:
    try:
        if path.stat().st_size > max_bytes:
            return None
        text = path.read_bytes().decode("utf-8")
    except (OSError, UnicodeDecodeError):
        return None
    if not text.strip() or "\x00" in text:
        return None
    lines = text.splitlines()
    if max(map(len, lines)) > 1000:  # minified or data
        return None
    head = "\n".join(lines[:5]).lower()
    if any(m in head for m in GENERATED_MARKERS):
        return None
    return text


def iter_code(roots: Iterable[str | Path], patterns: tuple[str, ...], max_bytes: int = 200_000) -> Iterator[tuple[str, str]]:
    """(relative path, text) for every matching source file, exact duplicates removed."""
    seen = set()
    for root in map(Path, roots):
        root = root.expanduser().resolve()
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS and not d.startswith("."))
            for f in sorted(filenames):
                if not matches(f, patterns):
                    continue
                p = Path(dirpath) / f
                text = read_source(p, max_bytes)
                if text is None:
                    continue
                h = hashlib.sha1(text.encode()).digest()
                if h in seen:
                    continue
                seen.add(h)
                yield str(p.relative_to(root)), text


def code_doc(rel: str, text: str) -> tuple[str, str, str]:
    return f"<|bos|><|file|>{rel}\n", "", chat.sanitize(text)


def is_val(key: str, val_frac: float) -> bool:
    return int(hashlib.sha1(key.encode()).hexdigest()[:8], 16) % 10_000 < val_frac * 10_000


class Corpus:
    def __init__(self, tokens: np.ndarray, offsets: np.ndarray):
        self.tokens, self.offsets = tokens, offsets  # offsets[d] = (header, context, completion, end)

    def __len__(self) -> int:
        return len(self.offsets)

    @classmethod
    def from_docs(cls, docs: Iterable[tuple[list[int], list[int], list[int]]], vocab_size: int) -> "Corpus":
        dtype = np.uint16 if vocab_size <= 65535 else np.uint32
        chunks, offs, pos = [], [], 0
        for h, c, k in docs:
            arr = np.concatenate([np.asarray(x, dtype=dtype) for x in (h, c, k)])
            offs.append((pos, pos + len(h), pos + len(h) + len(c), pos + len(arr)))
            chunks.append(arr)
            pos += len(arr)
        tokens = np.concatenate(chunks) if chunks else np.zeros(0, dtype)
        return cls(tokens, np.asarray(offs, dtype=np.int64).reshape(-1, 4))

    def save(self, d: Path) -> None:
        d.mkdir(parents=True, exist_ok=True)
        np.save(d / "tokens.npy", self.tokens)
        np.save(d / "offsets.npy", self.offsets)

    @classmethod
    def load(cls, d: Path) -> "Corpus":
        return cls(np.load(d / "tokens.npy", mmap_mode="r"), np.load(d / "offsets.npy"))

    def index(self, block_len: int) -> np.ndarray:
        """(doc, start) of every target block."""
        rows = [np.stack([np.full(len(s), d), s], 1) for d, (_, _, k, e) in enumerate(self.offsets)
                if len(s := np.arange(0, e - k, block_len))]
        return np.concatenate(rows).astype(np.int64) if rows else np.zeros((0, 2), np.int64)

    def example(self, d: int, s: int, block_len: int, prefix_len: int) -> tuple[list[int], list[int]]:
        h, c, k, e = (int(x) for x in self.offsets[d])
        header = self.tokens[h:c].tolist()
        keep = prefix_len - min(len(header), prefix_len // 2)
        body = self.tokens[max(c, k + s - keep):k + s].tolist()
        target = self.tokens[k + s:min(k + s + block_len, e)].tolist()
        return build_prefix(header, body, prefix_len), target + [PAD] * (block_len - len(target))

    def batch(self, rows: np.ndarray, block_len: int, prefix_len: int) -> tuple[np.ndarray, np.ndarray]:
        pre, tgt = zip(*(self.example(d, s, block_len, prefix_len) for d, s in rows))
        return np.asarray(pre, np.int64), np.asarray(tgt, np.int64)


def build_dataset(out: Path, code_roots: list[str], langs: list[str], *, infra: bool = False,
                  trajectories: Iterable[dict] = (), chat_cfg: ChatConfig | None = None,
                  bpe: BPE | None = None, vocab_size: int = 8192, val_frac: float = 0.01,
                  max_bytes: int = 200_000, chat_repeat: int = 1, max_context: int = 4096, log=print) -> dict:
    """max_context: context tokens kept per example. Only the last prefix_len are ever read, so this
    caps storage (otherwise quadratic in session length) and bounds the usable prefix_len."""
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    chat_cfg = chat_cfg or ChatConfig()
    if code_roots and not langs:
        raise ValueError("code roots given without languages (--lang)")
    pats = patterns_for(langs, infra) if langs else ()

    def code_items():
        return iter_code(code_roots, pats, max_bytes) if code_roots else iter(())

    chat_items = []  # (split key, (header, context, completion))
    for i, t in enumerate(trajectories):
        key = json.dumps(t["messages"][:2], sort_keys=True) + str(i)
        for ex in chat.training_examples(t["messages"], t.get("tools"), chat_cfg, allowed_tools=set(TOOL_NAMES)):
            chat_items.append((key, ex))

    if bpe is None:
        log(f"training BPE (vocab {vocab_size})")

        def sample(limit=200_000_000):
            n = 0
            for _, text in code_items():
                yield text
                n += len(text)
                if n > limit:
                    return
            for _, ex in chat_items:
                yield "".join(ex)
        bpe = BPE.train(sample(), vocab_size)
    bpe.save(out / "bpe.json")

    splits: dict[str, list] = {"train": [], "val": []}
    stats = {"files": 0, "chat_examples": len(chat_items)}
    dtype = np.uint16 if bpe.vocab_size <= 65535 else np.uint32

    def add_all(items, repeat=1, size=256):
        items = iter(items)
        while batch := [x for _, x in zip(range(size), items)]:
            enc = bpe.encode_batch([t for _, texts in batch for t in texts])
            for j, (key, texts) in enumerate(batch):
                h, c, k = enc[3 * j:3 * j + 3]
                c = c[-max_context:]
                if not texts[2].endswith("<|end|>"):
                    k = k + [EOS]
                doc = tuple(np.asarray(x, dtype) for x in (h, c, k))
                split = "val" if is_val(key, val_frac) else "train"
                splits[split].extend([doc] * (repeat if split == "train" else 1))

    def counted_code():
        for rel, text in code_items():
            stats["files"] += 1
            yield rel + str(len(text)), code_doc(rel, text)

    add_all(counted_code())
    add_all(chat_items, chat_repeat)
    for name, docs in splits.items():
        corpus = Corpus.from_docs(docs, bpe.vocab_size)
        corpus.save(out / name)
        stats[f"{name}_docs"], stats[f"{name}_tokens"] = len(corpus), int(len(corpus.tokens))
    meta = {"langs": langs, "infra": infra, "vocab_size": bpe.vocab_size, "chat": dataclasses.asdict(chat_cfg),
            "max_context": max_context, **stats}
    (out / "meta.json").write_text(json.dumps(meta, indent=2) + "\n")
    log(json.dumps(meta))
    return meta
