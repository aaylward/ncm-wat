def make_tree(root):
    files = {
        "svc/src/App.java": SAMPLE_CODE[0],
        "svc/copy/App.java": SAMPLE_CODE[0],  # exact duplicate
        "svc/pom.xml": "<project/>\n",
        "svc/README.md": "# readme\n",
        "svc/node_modules/x/Index.java": "class X {}\n",
        "svc/.hidden/H.java": "class H {}\n",
        "svc/gen/G.java": "// Code generated by protoc. DO NOT EDIT.\nclass G {}\n",
        "svc/Min.java": "class M {" + "int a;" * 300 + "}\n",
        "svc/Big.java": "class B {}\n" + "// x\n" * 50_000,
        "svc/Dockerfile": "FROM eclipse-temurin:21\n",
        "svc/api.proto": 'syntax = "proto3";\n',
    }
    for rel, text in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)


def test_iter_code_filters_and_dedupes(tmp_path):
    make_tree(tmp_path)
    got = dict(iter_code([tmp_path], patterns_for(["java"]), max_bytes=100_000))
    assert set(got) == {"svc/copy/App.java", "svc/pom.xml"} or set(got) == {"svc/src/App.java", "svc/pom.xml"}
    with_infra = dict(iter_code([tmp_path], patterns_for(["java"], infra=True), max_bytes=100_000))
    assert {"svc/Dockerfile", "svc/api.proto"} <= set(with_infra)


def test_corpus_windows_pin_header_and_slide_over_completion():
    B, P = 4, 8
    header, context, completion = [1, 2], [3], list(range(10, 20))  # 10 completion tokens -> 3 blocks
    c = Corpus.from_docs([(header, context, completion)], vocab_size=100)
    idx = c.index(B)
    assert idx.tolist() == [[0, 0], [0, 4], [0, 8]]
    pre, tgt = c.example(0, 0, B, P)
    assert pre == [PAD] * 5 + [1, 2, 3] and tgt == [10, 11, 12, 13]
    pre, tgt = c.example(0, 8, B, P)
    assert pre == [1, 2, 12, 13, 14, 15, 16, 17] and tgt == [18, 19, PAD, PAD]
    p, t = c.batch(idx, B, P)
    assert p.shape == (3, P) and t.shape == (3, B) and p.dtype == np.int64


def test_build_dataset_mixes_code_and_trajectories(tmp_path):
    make_tree(tmp_path / "src")
    traj = {"messages": [
        {"role": "user", "content": "list files"},
        {"role": "assistant", "content": None, "tool_calls": [
            {"id": "a", "type": "function", "function": {"name": "ls", "arguments": "{}"}}]},
        {"role": "tool", "tool_call_id": "a", "content": "App.java"},
        {"role": "assistant", "content": "One file."}], "tools": TOOL_SCHEMAS}
    meta = build_dataset(tmp_path / "ds", [str(tmp_path / "src")], ["java"], trajectories=[traj],
                         vocab_size=300, val_frac=0.0, chat_repeat=2, log=lambda *_: None)
    assert meta["files"] == 2 and meta["chat_examples"] == 2
    bpe = BPE.load(tmp_path / "ds" / "bpe.json")
    train = Corpus.load(tmp_path / "ds" / "train")
    assert len(train) + meta["val_docs"] == 2 + 2 * 2  # code docs + repeated chat docs
    ends = {int(train.tokens[e - 1]) for _, _, _, e in train.offsets}
    assert ends <= {EOS, END} and END in ends
    h, c, _, _ = train.offsets[0]
    assert FILE in train.tokens[h:c].tolist()
    # code text survives tokenization
    doc = next(d for d in range(len(train)) if "RestController" in bpe.decode(train.tokens[train.offsets[d][2]:train.offsets[d][3]].tolist()))
    _, _, k, e = train.offsets[doc]
    assert bpe.decode(train.tokens[k:e - 1].tolist()) == SAMPLE_CODE[0]
    assert json.loads((tmp_path / "ds" / "meta.json").read_text())["langs"] == ["java"]


def test_session_context_is_capped(tmp_path):
    long = {"messages": [{"role": "user", "content": "word " * 2000}, {"role": "assistant", "content": "ok"}],
            "tools": TOOL_SCHEMAS}
    build_dataset(tmp_path / "ds", [], [], trajectories=[long], vocab_size=300, val_frac=0.0,
                  max_context=64, log=lambda *_: None)
    _, c, k, _ = Corpus.load(tmp_path / "ds" / "train").offsets[0]
    assert k - c == 64


def test_reused_bpe_serializes_identically(tmp_path, bpe):
    """Runs refuse data whose bpe.json differs byte-for-byte, so load/save must be stable."""
    bpe.save(tmp_path / "a.json")
    BPE.load(tmp_path / "a.json").save(tmp_path / "b.json")
    assert (tmp_path / "a.json").read_bytes() == (tmp_path / "b.json").read_bytes()


